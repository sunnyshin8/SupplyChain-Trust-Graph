CREATE OR REPLACE SECURE VIEW GOVERNED.PARTS AS SELECT * FROM SOURCE.PARTS;
CREATE OR REPLACE SECURE VIEW GOVERNED.PLANTS AS SELECT * FROM SOURCE.PLANTS;
