-- SupplyChain Trust Graph · layered security zones
-- Additive migration: CORE remains a private compatibility/landing schema while
-- application roles move to purpose-specific governed, workflow, and audit zones.

USE DATABASE SUPPLYCHAIN_TRUST_GRAPH;

CREATE SCHEMA IF NOT EXISTS SOURCE WITH MANAGED ACCESS
  COMMENT = 'Private normalized source boundary over legacy CORE landing objects';
CREATE SCHEMA IF NOT EXISTS GOVERNED WITH MANAGED ACCESS
  COMMENT = 'Read-only governed entities, analytical views, and semantic views';
CREATE SCHEMA IF NOT EXISTS WORKFLOW WITH MANAGED ACCESS
  COMMENT = 'Mutable mitigation workflow state; no ERP or purchase-order execution';
CREATE SCHEMA IF NOT EXISTS AUDIT WITH MANAGED ACCESS
  COMMENT = 'Append-only attributable audit evidence';

-- SOURCE is intentionally not granted to either application role. Secure views
-- isolate the legacy landing schema without duplicating governed source records.
CREATE OR REPLACE SECURE VIEW SOURCE.SUPPLIERS AS SELECT * FROM CORE.SUPPLIERS;
CREATE OR REPLACE SECURE VIEW SOURCE.PARTS AS SELECT * FROM CORE.PARTS;
CREATE OR REPLACE SECURE VIEW SOURCE.PLANTS AS SELECT * FROM CORE.PLANTS;
CREATE OR REPLACE SECURE VIEW SOURCE.SUPPLIER_PARTS AS SELECT * FROM CORE.SUPPLIER_PARTS;
CREATE OR REPLACE SECURE VIEW SOURCE.INVENTORY AS SELECT * FROM CORE.INVENTORY;
CREATE OR REPLACE SECURE VIEW SOURCE.CUSTOMERS AS SELECT * FROM CORE.CUSTOMERS;
CREATE OR REPLACE SECURE VIEW SOURCE.SALES_ORDERS AS SELECT * FROM CORE.SALES_ORDERS;
CREATE OR REPLACE SECURE VIEW SOURCE.SHIPMENTS AS SELECT * FROM CORE.SHIPMENTS;
CREATE OR REPLACE SECURE VIEW SOURCE.SUPPLIER_DOCUMENTS AS SELECT * FROM CORE.SUPPLIER_DOCUMENTS;
CREATE OR REPLACE SECURE VIEW SOURCE.DISRUPTION_EVENTS AS SELECT * FROM CORE.DISRUPTION_EVENTS;

-- The runtime reads only these governed contracts. It receives no direct CORE
-- or SOURCE access, so later masking/row-access policies can be applied here.
