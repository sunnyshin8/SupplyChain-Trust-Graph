CREATE OR REPLACE SECURE VIEW GOVERNED.SALES_ORDERS AS SELECT * FROM SOURCE.SALES_ORDERS;
CREATE OR REPLACE SECURE VIEW GOVERNED.SHIPMENTS AS SELECT * FROM SOURCE.SHIPMENTS;
CREATE OR REPLACE SECURE VIEW GOVERNED.SUPPLIER_DOCUMENTS AS SELECT * FROM SOURCE.SUPPLIER_DOCUMENTS;
CREATE OR REPLACE SECURE VIEW GOVERNED.DISRUPTION_EVENTS AS SELECT * FROM SOURCE.DISRUPTION_EVENTS;
